-- Create skills table
CREATE TABLE reference.skills (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
  skill_name TEXT NOT NULL,
  category TEXT NOT NULL,
  aliases JSONB NOT NULL DEFAULT '[]'::jsonb,
  description TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  
  -- Composite unique constraint to allow same skill name in different categories
  CONSTRAINT unique_skill_per_category UNIQUE (skill_name, category)
);

-- Add comments
COMMENT ON TABLE reference.skills IS 'Master skills catalog - shared across entire platform. Each skill stored once per category, referenced by many users via junction table. Located in reference schema for clear separation of lookup data.';
COMMENT ON COLUMN reference.skills.skill_name IS 'Canonical skill name (e.g., Python, JavaScript) - unique within category';
COMMENT ON COLUMN reference.skills.category IS 'Skill category (e.g., Programming Language, Framework, Tool) - required for context';
COMMENT ON COLUMN reference.skills.aliases IS 'Common variations/aliases as JSONB array (e.g., ["Javascript", "JS"] for JavaScript)';
COMMENT ON COLUMN reference.skills.description IS 'Brief description of the skill in this category context';
COMMENT ON CONSTRAINT unique_skill_per_category ON reference.skills IS 'Allows same skill name in different categories to preserve industry-specific context';

